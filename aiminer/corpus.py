"""Named edge cases. Each item is either a canonical success or one scan code."""

from __future__ import annotations


def _case(
    name: str,
    text: str,
    *,
    canon: str | None = None,
    code: str | None = None,
    **limits: int,
) -> dict[str, object]:
    if (canon is None) == (code is None):
        raise ValueError(name)
    return {
        "name": name,
        "text": text,
        "canon": canon,
        "code": code,
        "limits": limits or None,
    }


